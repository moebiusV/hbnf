#!/usr/bin/env python3
"""bip39_to_hbnf.py -- the BIP-39 word lists as hbnf include files.

    python3 tools/bip39_to_hbnf.py corpus/bip39/wordlists grammars/bip39

reads the ten official lists (english.txt, ...) and writes one include file for
each, `grammars/bip39/<language>.hbnf`, that defines

    bip39-word    the 2048 words, as a union (`/`), in list order
    bip39-space   the separator between words of a phrase (U+3000 for
                  Japanese, a blank for the others: BIP-39's word list notes)

A word's value is its position in the list, 0 to 2047, which is what BIP-39
packs into 11 bits.  hbnf writes a union of words longest first, so that a
word is not taken for the beginning of a longer one, and keeps the values in
list order (HBNF_Grammar.Enum_Rank).  Nothing here sorts a list: several of the
official lists are not in code point order, and the order is the index.
"""
import os
import sys

LANGS = {
    "chinese_simplified": "Chinese (Simplified)",
    "chinese_traditional": "Chinese (Traditional)",
    "czech": "Czech",
    "english": "English",
    "french": "French",
    "italian": "Italian",
    "japanese": "Japanese",
    "korean": "Korean",
    "portuguese": "Portuguese",
    "spanish": "Spanish",
}


def words(path):
    with open(path, encoding="utf-8", newline="") as f:
        text = f.read()
    if "\r" in text:
        sys.exit("%s: carriage returns; the official lists use LF" % path)
    ws = text.split("\n")
    if ws and ws[-1] == "":
        ws.pop()
    if len(ws) != 2048:
        sys.exit("%s: %d words, BIP-39 lists have 2048" % (path, len(ws)))
    if len(set(ws)) != 2048:
        sys.exit("%s: a word appears twice" % path)
    for w in ws:
        if not w or w != w.strip() or '"' in w or "\\" in w or " " in w:
            sys.exit("%s: cannot write %r as a literal" % (path, w))
    return ws


def main(argv):
    if len(argv) != 3:
        sys.exit(__doc__)
    src, dst = argv[1], argv[2]
    os.makedirs(dst, exist_ok=True)
    for lang, title in LANGS.items():
        ws = words(os.path.join(src, lang + ".txt"))
        space = '"　"' if lang == "japanese" else '" "'
        out = []
        out.append("; bip39/%s.hbnf -- the BIP-39 %s word list." % (lang, title))
        out.append("; Generated by tools/bip39_to_hbnf.py from")
        out.append("; corpus/bip39/wordlists/%s.txt; do not edit." % lang)
        out.append(";")
        out.append("; bip39-word has the 2048 words.  A word's value is its place in the")
        out.append("; list, 0 to 2047 (the list is not always in code point order, and the")
        out.append("; place is the index, so nothing is sorted).  hbnf matches a word that")
        out.append("; begins another one after it, and keeps the values in list order.")
        out.append("")
        out.append("bip39-word = " + "\n           / ".join('"%s"' % w for w in ws))
        out.append("")
        out.append("; Between the words of a phrase.")
        out.append("bip39-space = " + space)
        with open(os.path.join(dst, lang + ".hbnf"), "w", encoding="utf-8",
                  newline="\n") as f:
            f.write("\n".join(out) + "\n")
        print("%s: %d words" % (lang, len(ws)))


if __name__ == "__main__":
    main(sys.argv)
