#!/usr/bin/env python3
"""cobol_reserved.py RESERVED.C > corpus/cobol/reserved.hbnf

Writes the rule `reserved-word`: the words COBOL reserves, taken from GnuCOBOL 3.2's cobc/reserved.c
(bench/cache/cobol, fetched by tools/cobol_fetch.sh).  A word is kept when its comment there names a COBOL
standard (1985, 2002, 2014, 2023); the vendors' extensions, and the words that are reserved only in some
contexts (marked C/S) or only in the communication section, are left out, so a program may use them as names."""
import re, sys

text = open(sys.argv[1], errors='replace').read()
a = text.index('default_reserved_words[] = {')
b = text.index('\n};', a)
entries = re.findall(r'\{\s*"([^"]+)"\s*,\s*\d\s*,\s*\d\s*,\s*[A-Za-z_0-9\-]+\s*,\s*/\*\s*([^*]*?)\s*\*/', text[a:b])
keep = []
for word, tag in entries:
    t = tag.replace('\n', ' ')
    if 'C/S' in t or 'xtension' in t or 'Communication' in t or 'ACU' in t or 'IBM' in t or 'Obsolete' in t:
        continue
    if re.search(r'\b(85|2002|2014|2023|200x)\b', t) and word not in keep:
        keep.append(word)
keep.sort()
print('; The words COBOL reserves (ISO/IEC 1989: 1985, 2002, 2014 and 2023), generated by tools/cobol_reserved.py from')
print('; GnuCOBOL 3.2\'s cobc/reserved.c; do not edit.  %d words.  A reserved word is no name, which is how a' % len(keep))
print('; statement list knows where it ends: ELSE, END-IF and the verbs are none of them a data name.')
print('prefix none')
print('whitespace none')
print('sensitivity string %i')
print()
line = 'reserved-word ='
first = True
for w in keep:
    piece = ' "%s"' % w if first else ' | "%s"' % w
    first = False
    if len(line) + len(piece) > 110:
        print(line)
        line = '              ' + piece.lstrip() if False else '             ' + piece
    else:
        line += piece
print(line)
