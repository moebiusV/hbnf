#!/usr/bin/env python3
"""gen.py FORMAT BYTES: a deterministic document of about BYTES bytes in JSON, TOML, YAML or XML,
the shape of the data these formats carry: a list of records with strings, integers, floats,
booleans, nested tables and lists (for XML, a product catalog: elements nested four deep,
attributes, text with entity and character references, CDATA, comments, an xml-stylesheet processing
instruction and a DOCTYPE before the root, a default namespace and a prefixed one, a few non-ASCII
words; no processing instruction inside an element, which TinyXML-2 refuses).  The same generator and seed give the same bytes, so every
tool reads the same file.  Written to standard output."""
import random, sys

WORDS = "alpha bravo charlie delta echo foxtrot golf hotel india juliet kilo lima mike november oscar papa quebec romeo sierra tango uniform victor whiskey xray yankee zulu".split()

def rec(r, i):
    return {
        "id": i,
        "name": "%s-%s-%d" % (r.choice(WORDS), r.choice(WORDS), i),
        "active": r.random() < .5,
        "score": round(r.uniform(0, 1000), 3),
        "count": r.randint(-100000, 100000),
        "tags": [r.choice(WORDS) for _ in range(r.randint(0, 5))],
        "owner": {"user": r.choice(WORDS), "uid": r.randint(1000, 60000),
                  "home": "/home/" + r.choice(WORDS)},
        "note": " ".join(r.choice(WORDS) for _ in range(r.randint(2, 9))),
    }

def json_doc(r, i):
    import json
    return json.dumps(rec(r, i), separators=(", ", ": "))

def toml_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def toml_doc(r, i):
    x = rec(r, i)
    return "\n".join([
        "[[record]]",
        "id = %d" % x["id"],
        "name = %s" % toml_str(x["name"]),
        "active = %s" % ("true" if x["active"] else "false"),
        "score = %s" % repr(x["score"]),
        "count = %d" % x["count"],
        "tags = [%s]" % ", ".join(toml_str(t) for t in x["tags"]),
        "note = %s" % toml_str(x["note"]),
        "owner = { user = %s, uid = %d, home = %s }" % (toml_str(x["owner"]["user"]), x["owner"]["uid"], toml_str(x["owner"]["home"])),
        "",
    ])

def yaml_doc(r, i):
    x = rec(r, i)
    tags = "".join("    - %s\n" % t for t in x["tags"]) if x["tags"] else ""
    return (
        "- id: %d\n  name: %s\n  active: %s\n  score: %s\n  count: %d\n"
        "  tags:\n%s  owner:\n    user: %s\n    uid: %d\n    home: %s\n  note: \"%s\"\n"
        % (x["id"], x["name"], "true" if x["active"] else "false", repr(x["score"]), x["count"],
           tags if tags else "    []\n" , x["owner"]["user"], x["owner"]["uid"], x["owner"]["home"], x["note"])
    )


UNI = ["caf\u00e9", "na\u00efve", "Z\u00fcrich", "\u0434\u0430", "\u65e5\u672c\u8a9e", "\u20ac5", "\u00fcber"]
INLINE = ["&amp;", "&lt;", "&gt;", "&quot;", "&apos;", "&#233;", "&#x20AC;", "&#65;"]

def xml_words(r, lo, hi):
    out = []
    for _ in range(r.randint(lo, hi)):
        x = r.random()
        out.append(r.choice(UNI) if x < .03 else r.choice(INLINE) if x < .09 else r.choice(WORDS))
    return " ".join(out)

def xml_attr(s):
    return s.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;")

def xml_doc(r, i):
    x = rec(r, i)
    o = ["  <product id=\"p%d\" sku=\"SKU-%05d\" status=\"%s\" dc:created=\"2026-%02d-%02d\">" % (
        i, r.randint(0, 99999), r.choice(["active", "draft", "discontinued"]), r.randint(1, 12), r.randint(1, 28)),
        "    <dc:title>%s</dc:title>" % xml_words(r, 2, 6),
        "    <price currency=\"%s\">%.2f</price>" % (r.choice(["USD", "EUR", "GBP"]), x["score"]),
        "    <stock warehouse=\"w%d\" qty=\"%d\" backorder=\"%s\"/>" % (r.randint(1, 9), abs(x["count"]) % 500, "true" if x["active"] else "false"),
        "    <description>%s <b>%s</b> %s</description>" % (xml_words(r, 3, 12), xml_words(r, 1, 3), xml_words(r, 2, 10)),
        "    <tags>" + "".join("<tag>%s</tag>" % t for t in x["tags"]) + "</tags>",
        "    <owner uid=\"%d\" home=\"%s\">%s</owner>" % (x["owner"]["uid"], xml_attr(x["owner"]["home"]), x["owner"]["user"])]
    if r.random() < .4:
        o.append("    <note><![CDATA[raw <b>markup</b> & %s]]></note>" % x["note"])
    if r.random() < .3:
        o.append("    <!-- %s -->" % x["note"])
    o.append("    <reviews>")
    for k in range(r.randint(0, 3)):
        o.append("      <review stars=\"%d\" author=\"%s\">%s</review>" % (r.randint(1, 5), r.choice(WORDS), xml_words(r, 3, 14)))
    o.append("    </reviews>")
    o.append("  </product>")
    return "\n".join(o)

fmt, target = sys.argv[1], int(sys.argv[2])
r = random.Random(20261024)
out, size, i = [], 0, 0
while size < target:
    d = {"json": json_doc, "toml": toml_doc, "yaml": yaml_doc, "xml": xml_doc}[fmt](r, i)
    out.append(d)
    size += len(d.encode("utf-8")) + 2
    i += 1
if fmt == "xml":
    head = ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<?xml-stylesheet type="text/xsl" href="catalog.xsl"?>\n<!-- generated by bench/formats/gen.py -->\n'
            '<!DOCTYPE catalog SYSTEM "catalog.dtd">\n'
            '<catalog xmlns="urn:hbnf:bench:catalog" xmlns:dc="http://purl.org/dc/elements/1.1/" version="1.0">\n')
    sys.stdout.buffer.write((head + "\n".join(out) + "\n</catalog>\n").encode("utf-8"))
elif fmt == "json":
    sys.stdout.write("[\n" + ",\n".join(out) + "\n]\n")
else:
    sys.stdout.write("\n".join(out) + "\n")
