#!/usr/bin/env python3
"""gen-pow5.py -- write runtime/hbnf_pow5.h: the 128-bit approximations of the powers of five that
the Eisel-Lemire conversion of decimal text to a double (runtime/hbnf_scalar.h) multiplies by.

For each q from -342 to 308 the table holds two 64-bit words, the high word first, of a 128-bit number whose
top bit is set: 5^q for q >= 0 (cut off after 128 bits), and the reciprocal of 5^-q for q < 0 (rounded up).
Exact integer arithmetic; nothing here is floating point.
    python3 scripts/gen-pow5.py > runtime/hbnf_pow5.h"""
LO, HI = -342, 308
rows = []
for q in range(LO, HI + 1):
    if q >= 0:
        v = 5 ** q
        b = v.bit_length()
        m = v << (128 - b) if b <= 128 else v >> (b - 128)
    else:
        d = 5 ** -q
        b = d.bit_length()
        m = -((-(1 << (b - 1 + 128))) // d)             # ceil(2^(b-1+128) / 5^-q): 128 bits, top bit set
        assert (1 << 127) <= m < (1 << 128), q
    rows.append((m >> 64, m & ((1 << 64) - 1)))
print("/* hbnf_pow5.h -- generated by scripts/gen-pow5.py; do not edit.  The powers of five from 5^-342 to 5^308 as")
print("   128-bit numbers with the top bit set: two words each, the high word first. */")
print("#ifndef HBNF_POW5_H")
print("#define HBNF_POW5_H")
print("#include <stdint.h>")
print("#define HBNF_POW5_MIN (%d)" % LO)
print("#define HBNF_POW5_MAX (%d)" % HI)
print("static const uint64_t hbnf_pow5[%d] = {" % (2 * len(rows)))
for i, (h, l) in enumerate(rows):
    print("    0x%016XULL, 0x%016XULL,%s" % (h, l, "  /* 5^%d */" % (LO + i) if (LO + i) % 50 == 0 else ""))
print("};")
print("#endif")
