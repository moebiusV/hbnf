#!/usr/bin/env python3
"""idtables.py [DerivedCoreProperties.txt] > js-unicode.hbnf: the non-ASCII code points of ECMAScript's IdentifierStart and
IdentifierPart (ECMA-262 12.7), as ranges, from the Unicode Character Database.

IdentifierStart is UnicodeIDStart (the property ID_Start) and `$` and `_`; IdentifierPart is UnicodeIDContinue (ID_Continue),
`$`, U+200C and U+200D.  The properties are read from DerivedCoreProperties.txt of Unicode 16.0.0 (the file is fetched
from unicode.org when no path is given, and its sha256 is checked).  Only the code points above 127 are written: the ASCII
ones are in js-tokens.hbnf.

  python3 corpus/js/idtables.py > corpus/js/js-unicode.hbnf
"""
import hashlib
import re
import sys
import textwrap
import urllib.request

URL = 'https://www.unicode.org/Public/16.0.0/ucd/DerivedCoreProperties.txt'
SHA = '39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd'

if len(sys.argv) > 1:
    data = open(sys.argv[1], 'rb').read()
else:
    data = urllib.request.urlopen(URL).read()
if hashlib.sha256(data).hexdigest() != SHA:
    sys.exit('idtables.py: DerivedCoreProperties.txt is not the file of Unicode 16.0.0 (sha256 differs)')

prop = {'ID_Start': set(), 'ID_Continue': set()}
for line in data.decode('utf-8').split('\n'):
    m = re.match(r'([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(ID_Start|ID_Continue)\b', line)
    if m:
        lo = int(m.group(1), 16)
        hi = int(m.group(2) or m.group(1), 16)
        prop[m.group(3)].update(range(lo, hi + 1))
prop['ID_Continue'].update((0x200C, 0x200D))


def ranges(cps):
    out = []
    for c in sorted(cps):
        if c < 0x80:
            continue
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def fmt(rs):
    return ' | '.join('0x%X' % lo if lo == hi else '0x%X..0x%X' % (lo, hi) for lo, hi in rs)


print('; Generated by idtables.py from DerivedCoreProperties.txt of Unicode 16.0.0: do not edit.')
print('; The code points above 127 that ECMAScript (ECMA-262 12.7) allows to start an identifier (id-start-high: ID_Start) and')
print('; to continue one (id-part-high: ID_Continue, and U+200C and U+200D).')
print('whitespace none')
print('prefix none')
for name, key in (('id-start-high', 'ID_Start'), ('id-part-high', 'ID_Continue')):
    body = textwrap.fill(fmt(ranges(prop[key])), 118, subsequent_indent='    ', break_long_words=False, break_on_hyphens=False)
    print('%s = %s' % (name, body))
